#!/usr/bin/env python3
"""
Keeps the bird pipeline's Python packages up to date without surprises.

requirements.in / requirements-ai.in say *what* is needed. requirements.txt /
requirements-ai.txt are generated lock files with the exact versions that last
passed the checks below; the dev container always installs from them.

About once a month (checked at the start of an import), this:
  1. builds the newest versions in a scratch venv (/tmp/venv-birds-candidate),
  2. runs the health check (doctor.py) there, and, if AI suggestions work today,
     a quick accuracy test that must match today's results,
  3. only if both pass, writes new lock files and installs them into the live venv.
If anything fails, nothing changes: the working versions stay, a one-line notice is
printed (details in .deps-update.log), and it tries again in a week.

    rake birds:update_deps            # check now
    rake birds:import -- --no-update  # skip the check for one run (or BIRDS_NO_UPDATE=1)

For testing the failure path, BIRDS_UPDATE_TEST_FAIL=1 makes the candidate fail its
checks on purpose: nothing is changed, and the failure is recorded as usual.
"""

import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

SCRIPT_DIR = Path(__file__).resolve().parent

CORE_IN = SCRIPT_DIR / "requirements.in"
AI_IN = SCRIPT_DIR / "requirements-ai.in"
CORE_LOCK = SCRIPT_DIR / "requirements.txt"
AI_LOCK = SCRIPT_DIR / "requirements-ai.txt"
STATE_PATH = SCRIPT_DIR / ".deps-state.json"
LOG_PATH = SCRIPT_DIR / ".deps-update.log"

# The only directory this script ever deletes, and only this exact path
CANDIDATE_VENV = Path("/tmp/venv-birds-candidate")

CHECK_EVERY_DAYS = 30
RETRY_FAILED_DAYS = 7
EVAL_PHOTOS = 30

LOCK_HEADER = (
    "# GENERATED by scripts/birds/update_deps.py: the exact versions that last passed\n"
    "# the health check and accuracy test. Don't edit; change {source} instead.\n"
)


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_state() -> Dict:
    try:
        return json.loads(STATE_PATH.read_text(encoding="utf-8"))
    except Exception:
        return {}


def write_state(result: str, detail: str, changes: Optional[List[str]] = None) -> None:
    STATE_PATH.write_text(json.dumps({
        "last_check": datetime.datetime.now().isoformat(timespec="seconds"),
        "result": result,  # "updated", "up-to-date" or "failed"
        "detail": detail,
        "changes": changes or [],
    }, indent=2) + "\n", encoding="utf-8")


def due() -> bool:
    state = read_state()
    try:
        age = datetime.datetime.now() - datetime.datetime.fromisoformat(state["last_check"])
    except Exception:
        return True
    wait = RETRY_FAILED_DAYS if state.get("result") == "failed" else CHECK_EVERY_DAYS
    return age >= datetime.timedelta(days=wait)


def online() -> bool:
    try:
        urllib.request.urlopen("https://pypi.org/simple/pip/", timeout=5).close()
        return True
    except Exception:
        return False


class Log:
    def __init__(self) -> None:
        LOG_PATH.write_text(f"Package update check, {datetime.datetime.now().isoformat(timespec='seconds')}\n", encoding="utf-8")

    def run(self, cmd: List[str], **kwargs) -> subprocess.CompletedProcess:
        result = subprocess.run(cmd, capture_output=True, text=True, cwd=SCRIPT_DIR.parents[1], **kwargs)
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(f"\n$ {' '.join(map(str, cmd))}\n{result.stdout}{result.stderr}(exit {result.returncode})\n")
        return result


def in_names(path: Path) -> List[str]:
    """Package names listed in a requirements.in file."""
    names = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            names.append(re.split(r"[\s<>=!~\[;]", line, 1)[0])
    return names


# Run inside a venv's own python: prints {name: [version, [dependency names]]}
_INVENTORY = r"""
import json, re
from importlib import metadata
out = {}
for d in metadata.distributions():
    deps = []
    for req in d.requires or []:
        if "extra ==" in req:
            continue
        deps.append(re.split(r"[\s<>=!~\[;(]", req, 1)[0])
    out[d.metadata["Name"]] = [d.version, deps]
print(json.dumps(out))
"""


def locks_for(python: Path) -> Tuple[List[str], List[str]]:
    """(core lock lines, AI lock lines) for everything installed in the given venv."""
    inventory = json.loads(subprocess.run([str(python), "-c", _INVENTORY], capture_output=True, text=True, check=True).stdout)
    installed = {_norm(name): (name, version, deps) for name, (version, deps) in inventory.items()}

    def closure(roots: List[str]) -> Set[str]:
        seen: Set[str] = set()
        todo = [_norm(r) for r in roots]
        while todo:
            n = todo.pop()
            if n in seen or n not in installed:
                continue
            seen.add(n)
            todo.extend(_norm(d) for d in installed[n][2])
        return seen

    core = closure(in_names(CORE_IN) + ["pip"])
    ai = closure(in_names(AI_IN)) - core

    def pins(names: Set[str]) -> List[str]:
        return sorted((f"{installed[n][0]}=={installed[n][1]}" for n in names), key=str.lower)

    return pins(core), pins(ai)


def write_locks(core: List[str], ai: List[str]) -> None:
    CORE_LOCK.write_text(LOCK_HEADER.format(source=CORE_IN.name) + "\n".join(core) + "\n", encoding="utf-8")
    index = next(line for line in AI_IN.read_text(encoding="utf-8").splitlines() if line.startswith("--extra-index-url"))
    AI_LOCK.write_text(LOCK_HEADER.format(source=AI_IN.name) + index + "\n" + "\n".join(ai) + "\n", encoding="utf-8")


def lock_pins(path: Path) -> Dict[str, str]:
    pins = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "==" in line and not line.startswith("#"):
            name, version = line.split("==", 1)
            pins[_norm(name)] = version.strip()
    return pins


def evaluate(python: Path, log: Log) -> Optional[Dict]:
    result = log.run([str(python), str(SCRIPT_DIR / "evaluate_model.py"), "--json", "--limit", str(EVAL_PHOTOS)])
    try:
        return json.loads(result.stdout.strip().splitlines()[-1])
    except Exception:
        return None


def remove_candidate() -> None:
    assert CANDIDATE_VENV == Path("/tmp/venv-birds-candidate")
    if CANDIDATE_VENV.exists():
        shutil.rmtree(CANDIDATE_VENV)


def maybe_update(force: bool = False) -> bool:
    """
    Runs the update check if it's due (or forced). Returns True if new versions were
    installed into this venv, so the caller can restart on them.
    """
    if os.environ.get("BIRDS_NO_UPDATE") and not force:
        return False
    if not force and not due():
        return False
    if not online():
        if force:
            print("Package update check skipped: no internet connection.")
        return False  # Try again next run

    print(f"Checking for package updates (a few minutes, at most once every {CHECK_EVERY_DAYS} days)...")
    log = Log()
    live_python = Path(sys.executable)
    try:
        return _update(log, live_python)
    finally:
        remove_candidate()


def _update(log: Log, live_python: Path) -> bool:
    def reject(reason: str) -> bool:
        write_state("failed", reason)
        print(f"Package update skipped: {reason}. Staying on the current versions "
              f"(they still work); details in {LOG_PATH.relative_to(SCRIPT_DIR.parents[1])}. "
              f"Will try again in {RETRY_FAILED_DAYS} days.")
        return False

    # Does AI work today? Then the new versions must keep it working, and as accurately.
    ai_today = log.run([str(live_python), str(SCRIPT_DIR / "doctor.py"), "--require-ai"]).returncode == 0

    remove_candidate()
    if log.run([str(live_python), "-m", "venv", str(CANDIDATE_VENV)]).returncode != 0:
        return reject("couldn't create the scratch environment")
    candidate = CANDIDATE_VENV / "bin" / "python"
    log.run([str(candidate), "-m", "pip", "install", "--upgrade", "pip"])
    if log.run([str(candidate), "-m", "pip", "install", "--upgrade", "-r", str(CORE_IN)]).returncode != 0:
        return reject("the newest core packages failed to install")
    ai_installed = log.run([str(candidate), "-m", "pip", "install", "--upgrade", "-r", str(AI_IN)]).returncode == 0
    if ai_today and not ai_installed:
        return reject("the newest AI packages failed to install")

    if os.environ.get("BIRDS_UPDATE_TEST_FAIL"):
        return reject("simulated failure (BIRDS_UPDATE_TEST_FAIL is set)")

    doctor = [str(candidate), str(SCRIPT_DIR / "doctor.py")] + (["--require-ai"] if ai_today else [])
    if log.run(doctor).returncode != 0:
        return reject("the newest versions failed the health check")

    if ai_today:
        before, after = evaluate(live_python, log), evaluate(candidate, log)
        if not after:
            return reject("the newest versions couldn't run the accuracy test")
        if before and after["top3"] < before["top3"] - 1:
            return reject(f"accuracy dropped with the newest versions ({after['top3']} vs "
                          f"{before['top3']} of {EVAL_PHOTOS} photos right in the top 3)")

    core, ai = locks_for(candidate)
    if not ai_installed:
        ai = [line for line in AI_LOCK.read_text(encoding="utf-8").splitlines() if "==" in line and not line.startswith("#")]
    old_pins = {**lock_pins(CORE_LOCK), **lock_pins(AI_LOCK)}
    new_pins = {_norm(l.split("==")[0]): l.split("==")[1] for l in core + ai}
    changes = sorted(f"{name} {old_pins.get(name, '(new)')} → {version}"
                     for name, version in new_pins.items() if old_pins.get(name) != version)
    if not changes:
        write_state("up-to-date", "already on the newest versions")
        print("Packages are already up to date.")
        return False

    # Switch the live venv over, putting the old lock files back if that fails
    old_core, old_ai = CORE_LOCK.read_text(encoding="utf-8"), AI_LOCK.read_text(encoding="utf-8")
    write_locks(core, ai)
    if log.run([str(live_python), "-m", "pip", "install", "-r", str(CORE_LOCK), "-r", str(AI_LOCK)]).returncode != 0:
        CORE_LOCK.write_text(old_core, encoding="utf-8")
        AI_LOCK.write_text(old_ai, encoding="utf-8")
        log.run([str(live_python), "-m", "pip", "install", "-r", str(CORE_LOCK), "-r", str(AI_LOCK)])
        return reject("installing the new versions into the live environment failed (restored the old ones)")

    write_state("updated", f"{len(changes)} package(s) updated", changes)
    shown = ", ".join(changes[:6]) + (f", and {len(changes) - 6} more" if len(changes) > 6 else "")
    print(f"Updated {len(changes)} package(s): {shown}.")
    print("The lock files (scripts/birds/requirements*.txt) changed; commit them when convenient.")
    return True


def status_line() -> str:
    state = read_state()
    if not state:
        return "never checked"
    return f"{state.get('last_check', '?')[:10]}: {state.get('result', '?')} ({state.get('detail', '')})"


def main() -> None:
    parser = argparse.ArgumentParser(description="Update the bird pipeline's Python packages, safely.")
    parser.add_argument("--status", action="store_true", help="Show the last check's result and exit")
    args = parser.parse_args()
    if args.status:
        print(f"Last package update check: {status_line()}")
        return
    maybe_update(force=True)
    print(f"Last package update check: {status_line()}")


if __name__ == "__main__":
    main()
